// @ts-check
/**
 * starlight.mjs
 *
 * The config factory behind every per-package docs site. A generated
 * apps/docs/<slug>/astro.config.mjs calls defineDocsSite with the site's row
 * from manifest.mjs; everything shared — the smithers.sh branding, the
 * Google Fonts head tags, the expressive-code font, the social links, and the
 * sidebar — lives here so 53 sites stay identical by construction.
 *
 * The factory takes the starlight integration as a parameter rather than
 * importing it: @astrojs/starlight's entry is a raw .ts file, and astro's
 * config loader only compiles it when the import comes from the config file
 * itself (vite never externalizes a .ts module, but a linked workspace
 * package's .mjs IS externalized to node, which refuses to strip types under
 * node_modules). The generated config therefore imports starlight directly
 * and passes it in; this module imports nothing but node builtins.
 *
 * The sidebar is computed from the synced content tree at config-eval time:
 * docs authors place files under the source package's docs/ and the sidebar
 * follows. The shape:
 *
 *   - "Start here": Overview (index), installation, quickstart, when present.
 *   - Every other top-level page, alphabetical (testing, troubleshooting...).
 *   - One autogenerated group per content directory: the standard five
 *     (guides, tutorials, concepts, reference, troubleshooting) in that
 *     order, then any other directory, alphabetical. Ordering inside a group
 *     comes from each page's `sidebar.order` frontmatter, then its title.
 */
import { existsSync, readdirSync } from "node:fs"
import { join } from "node:path"

/** The standard groups, in sidebar order, with their labels. */
const standardGroups = [
  ["guides", "Guides"],
  ["tutorials", "Tutorials"],
  ["concepts", "Concepts"],
  ["reference", "Reference"],
  ["troubleshooting", "Troubleshooting"]
]

/** Whether <root>/<name>.md (or .mdx) exists. */
const hasPage = (root, name) =>
  existsSync(join(root, `${name}.md`)) || existsSync(join(root, `${name}.mdx`))

/** Whether a directory holds at least one page, at any depth. */
const dirHasPages = (root, dir) => {
  const walk = (d) =>
    readdirSync(d, { withFileTypes: true }).some((entry) =>
      entry.isDirectory() ? walk(join(d, entry.name)) : /\.mdx?$/.test(entry.name)
    )
  const abs = join(root, dir)
  return existsSync(abs) && walk(abs)
}

/** "ui-styleguide" -> "Ui Styleguide": directory labels for non-standard groups. */
const titleCase = (name) =>
  name.split(/[-_]/).map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(" ")

/**
 * The sidebar for the synced content tree at `contentRoot`. Returns an empty
 * sidebar before the first sync so a site still configures (but not builds
 * usefully) with no content.
 */
export function sidebarFor(contentRoot) {
  if (!existsSync(contentRoot)) return []
  const sidebar = []
  const startHere = []
  if (hasPage(contentRoot, "index")) startHere.push({ label: "Overview", link: "/" })
  if (hasPage(contentRoot, "installation")) startHere.push({ slug: "installation" })
  if (hasPage(contentRoot, "quickstart")) startHere.push({ slug: "quickstart" })
  if (startHere.length > 0) sidebar.push({ label: "Start here", items: startHere })
  const listing = readdirSync(contentRoot, { withFileTypes: true })
  // Top-level pages that are not Start-here entries, alphabetical by slug.
  const extras = listing
    .filter((entry) => entry.isFile() && /\.mdx?$/.test(entry.name))
    .map((entry) => entry.name.replace(/\.mdx?$/, ""))
    .filter((name) => !["index", "installation", "quickstart"].includes(name))
    .sort()
  for (const slug of extras) sidebar.push({ slug })
  // Directory groups: the standard five in order, then the rest alphabetical.
  const dirs = listing.filter((entry) => entry.isDirectory()).map((entry) => entry.name)
  const standard = standardGroups.filter(([dir]) => dirs.includes(dir))
  const others = dirs
    .filter((dir) => !standardGroups.some(([standardDir]) => standardDir === dir))
    .sort()
    .map((dir) => [dir, titleCase(dir)])
  for (const [dir, label] of [...standard, ...others]) {
    if (dirHasPages(contentRoot, dir)) sidebar.push({ label, autogenerate: { directory: dir } })
  }
  return sidebar
}

/**
 * The astro config for one package's docs site.
 *
 * `sourceDir` is the repo-relative package directory (for example
 * "packages/smithers/flows/flow"); the edit-link base points at its docs/
 * tree on GitHub, and sync-content.mjs pins each page's exact source file
 * through the page's `editUrl` frontmatter. `contentDir` defaults to
 * ./src/content/docs under the process working directory; generated configs
 * pass it anchored at their own import.meta.url so the sidebar resolves the
 * same tree no matter where astro is invoked from.
 */
export function defineDocsSite({ starlight, slug, title, description, sourceDir, contentDir }) {
  const contentRoot = contentDir ?? join(process.cwd(), "src/content/docs")
  return {
    site: `https://${slug}.smithers.sh`,
    output: "static",
    integrations: [
      starlight({
        title,
        description,
        logo: { src: "./src/docs-assets/logo.png", alt: "Smithers" },
        favicon: "/favicon.png",
        customCss: ["./src/styles/starlight.css"],
        // The same pairing as smithers.sh: Inter for prose, IBM Plex Mono for
        // code, from Google Fonts with a system stack behind each in
        // src/styles/starlight.css (generated from shared/starlight.css).
        head: [
          { tag: "link", attrs: { rel: "preconnect", href: "https://fonts.googleapis.com" } },
          { tag: "link", attrs: { rel: "preconnect", href: "https://fonts.gstatic.com", crossorigin: true } },
          {
            tag: "link",
            attrs: {
              rel: "stylesheet",
              href:
                "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&display=swap"
            }
          }
        ],
        expressiveCode: {
          styleOverrides: {
            codeFontFamily: "\"IBM Plex Mono\", ui-monospace, SFMono-Regular, Menlo, Consolas, monospace"
          }
        },
        social: [
          { icon: "external", label: "smithers.sh", href: "https://smithers.sh" },
          { icon: "github", label: "GitHub", href: "https://github.com/smithersai/smithers" }
        ],
        editLink: {
          baseUrl: `https://github.com/smithersai/smithers/edit/main/${sourceDir}/docs/`
        },
        sidebar: sidebarFor(contentRoot)
      })
    ]
  }
}
